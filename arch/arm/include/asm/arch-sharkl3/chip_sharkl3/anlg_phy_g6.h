/* REG_ANLG_PHY_G6_ANALOG_DESKEWPLL_DESPLL_CTRL0 */

#define BIT_ANLG_PHY_G6_ANALOG_DESKEWPLL_DESPLL_IBIAS(x)          (((x) & 0x3) << 5)
