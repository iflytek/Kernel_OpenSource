static int lcd_hx83102_1197_boe_option_power(int on)
{
	printf("lcd_hx83102_1197_boe_option power on! %d \n",on);
	//aw37504_read_reg();
	lcd_use_sc2703l_to_power_on(false);

	sprd_gpio_request(NULL, CONFIG_LCM_GPIO_RSTN);
	sprd_gpio_request(NULL, CONFIG_LCM_TP_RSTN);
	sprd_gpio_request(NULL, AVDDVSP_EN);
	sprd_gpio_request(NULL, AVEEVSN_EN);
	sprd_gpio_request(NULL, LCM_EN);
	sprd_gpio_request(NULL, LCM_BL_EN);

	if (on) {
		sprd_gpio_direction_output(NULL, CONFIG_LCM_GPIO_RSTN, 0);
		sprd_gpio_direction_output(NULL, CONFIG_LCM_TP_RSTN, 0);
		mdelay(10);

		sprd_gpio_direction_output(NULL, LCM_BL_EN, 1);
		mdelay(10);

		sprd_gpio_direction_output(NULL, LCM_EN, 1);
		mdelay(5);

		sprd_gpio_direction_output(NULL, CONFIG_LCM_TP_RSTN, 1);
		mdelay(2);
		aw37504_write_reg();
		mdelay(2);

		sprd_gpio_direction_output(NULL, AVDDVSP_EN, 1);
		mdelay(2);
		sprd_gpio_direction_output(NULL, AVEEVSN_EN, 1);
		mdelay(10);

		sprd_gpio_direction_output(NULL, CONFIG_LCM_GPIO_RSTN, 1);
		mdelay(5);
		sprd_gpio_direction_output(NULL, CONFIG_LCM_GPIO_RSTN, 0);
		mdelay(5);
		sprd_gpio_direction_output(NULL, CONFIG_LCM_GPIO_RSTN, 1);
	} else {
		sprd_gpio_direction_output(NULL, LCM_BL_EN, 0);
		sprd_gpio_direction_output(NULL, AVDDVSP_EN, 0);
		sprd_gpio_direction_output(NULL, AVEEVSN_EN, 0);
		sprd_gpio_direction_output(NULL, CONFIG_LCM_GPIO_RSTN, 0);
		sprd_gpio_direction_output(NULL, LCM_EN, 0);
		mdelay(50);
	}

	return 0;
}

