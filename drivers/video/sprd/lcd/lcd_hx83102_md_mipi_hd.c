static int lcd_hx83102_md_option_readid(void)
{

	struct sprd_dsi *dsi = &dsi_device;
	uint8_t read_buf0;

	mipi_dsi_lp_cmd_enable(dsi, true);
	mipi_dsi_send_cmds(dsi,readid_begin);
	mipi_dsi_set_max_return_size(dsi, 1);
	mipi_dsi_dcs_read(dsi, 0xda, &read_buf0, 1);
	mipi_dsi_send_cmds(dsi,readid_end);

	if(0x2 == read_buf0) {
		pr_info("lcd_hx83102_md_option read id success! 0xda==0x%x\n",read_buf0);
		mdelay(20);
		return 0;
	}

	pr_info("lcd_hx83102_md_option read id fail:0x%x!\n", read_buf0);
	return -1;
}

